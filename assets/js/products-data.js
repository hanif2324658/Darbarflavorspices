  async syncFromCloud() {
    try {
      if (typeof window === 'undefined') return;
      const cfg = this.getStoreConfig();
      if (!cfg || !cfg.cloudSyncUrl) return;

      const headers = {};
      if (cfg.cloudApiKey) {
        headers['X-Master-Key'] = cfg.cloudApiKey;
        headers['Authorization'] = 'Bearer ' + cfg.cloudApiKey;
      }

      let fetchUrl = cfg.cloudSyncUrl;
      // Support direct Firebase Realtime Database REST URL
      if (fetchUrl.includes('firebaseio.com') && cfg.cloudApiKey && !fetchUrl.includes('auth=')) {
        fetchUrl += (fetchUrl.includes('?') ? '&' : '?') + 'auth=' + encodeURIComponent(cfg.cloudApiKey);
      }

      const res = await fetch(fetchUrl, { headers });
      if (res.ok) {
        const data = await res.json();
        const cloudProducts = (data && data.record && data.record.products) || 
                              (data && data.products) || 
                              (Array.isArray(data) ? data : null);
        if (Array.isArray(cloudProducts) && cloudProducts.length > 0) {
          this.saveProducts(cloudProducts);
        }
        const cloudCategories = (data && data.record && data.record.categories) || 
                                (data && data.categories);
        if (Array.isArray(cloudCategories) && cloudCategories.length > 0) {
          this.saveCategories(cloudCategories);
        }
        const cloudReviews = (data && data.record && data.record.reviews) || 
                             (data && data.reviews);
        if (Array.isArray(cloudReviews) && cloudReviews.length > 0) {
          this.saveReviews(cloudReviews);
        }
        const cloudConfig = (data && data.record && data.record.storeConfig) || 
                            (data && data.storeConfig);
        if (cloudConfig && typeof cloudConfig === 'object') {
          this.saveStoreConfig(cloudConfig);
        }
      }
    } catch (e) {}
  },

